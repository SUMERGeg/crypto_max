import { writeFile } from "node:fs/promises";

const DAY = 24 * 60 * 60 * 1000;
const outputPath = new URL("../apps/api/src/scenario-points-extra.ts", import.meta.url);

const scenarios = [
  { id: "boom-2017-2018", start: "2017-08-17", end: "2018-12-31", assets: ["BTC", "ETH"] },
  { id: "winter-2021-2022", start: "2021-03-01", end: "2023-01-01", assets: ["BTC", "ETH", "SOL"] },
  { id: "recovery-2023-2024", start: "2023-01-01", end: "2025-01-01", assets: ["BTC", "ETH", "SOL"] },
  { id: "modern-2024-2025", start: "2024-07-01", end: "2025-07-01", assets: ["BTC", "ETH", "SOL"] },
];

const formatCbrDate = (iso) => iso.split("-").reverse().join("/");
const isoDay = (timestamp) => new Date(timestamp).toISOString().slice(0, 10);

async function fetchRates(start, end) {
  const from = isoDay(Date.parse(start) - 10 * DAY);
  const url = `https://www.cbr.ru/scripts/XML_dynamic.asp?date_req1=${formatCbrDate(from)}&date_req2=${formatCbrDate(end)}&VAL_NM_RQ=R01235`;
  const response = await fetch(url, { headers: { "User-Agent": "CryptoEducationDataset/1.0" } });
  if (!response.ok) throw new Error(`CBR ${response.status}`);
  const xml = await response.text();
  const rates = [...xml.matchAll(/<Record Date="(\d{2})\.(\d{2})\.(\d{4})"[^>]*>[\s\S]*?<Nominal>([^<]+)<\/Nominal>[\s\S]*?<Value>([^<]+)<\/Value>[\s\S]*?<\/Record>/g)]
    .map((match) => ({
      at: `${match[3]}-${match[2]}-${match[1]}`,
      rate: Number(match[5].replace(",", ".")) / Number(match[4].replace(",", ".")),
    }))
    .sort((a, b) => a.at.localeCompare(b.at));
  if (!rates.length) throw new Error(`No CBR rates for ${start}..${end}`);
  return rates;
}

async function fetchKlines(symbol, start, end) {
  const startTime = Date.parse(`${start}T00:00:00Z`);
  const endTime = Date.parse(`${end}T00:00:00Z`) + DAY;
  const url = new URL("https://api.binance.com/api/v3/klines");
  url.searchParams.set("symbol", `${symbol}USDT`);
  url.searchParams.set("interval", "1d");
  url.searchParams.set("startTime", String(startTime));
  url.searchParams.set("endTime", String(endTime));
  url.searchParams.set("limit", "1000");
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Binance ${symbol} ${response.status}`);
  const rows = await response.json();
  return rows.map((row) => ({ at: isoDay(Number(row[0])), closeUsd: Number(row[4]) }));
}

function convertToRub(klines, rates) {
  let rateIndex = 0;
  return klines.map((point) => {
    while (rateIndex + 1 < rates.length && rates[rateIndex + 1].at <= point.at) rateIndex += 1;
    return { at: `${point.at}T00:00:00Z`, priceRub: Math.round(point.closeUsd * rates[rateIndex].rate * 100) / 100 };
  });
}

const datasets = {};
for (const scenario of scenarios) {
  const rates = await fetchRates(scenario.start, scenario.end);
  datasets[scenario.id] = {};
  for (const asset of scenario.assets) {
    const klines = await fetchKlines(asset, scenario.start, scenario.end);
    datasets[scenario.id][asset] = convertToRub(klines, rates);
  }
}

const source = `// Generated by scripts/generate-extra-scenario-points.mjs.\n// Binance daily USDT close converted with the official CBR USD/RUB rate.\nexport const extraScenarioPoints: Record<string, Record<string, Array<{ at: string; priceRub: number }>>> = ${JSON.stringify(datasets, null, 2)};\n`;
await writeFile(outputPath, source, "utf8");

for (const [scenarioId, assets] of Object.entries(datasets)) {
  console.log(scenarioId, Object.fromEntries(Object.entries(assets).map(([symbol, points]) => [symbol, points.length])));
}
