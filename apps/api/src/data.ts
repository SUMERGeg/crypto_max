function learningPages(item: LessonRecord): LessonPage[] {
  const [firstCheck, secondCheck, finalQuestion] = item.quiz.questions;
  if (!firstCheck || !secondCheck || !finalQuestion) return [];

  const checkpoint = (quizQuestion: QuizQuestion, order: number): LessonCheckpointPage => ({
    id: `${item.id}-checkpoint-${order}`,
    kind: "CHECKPOINT",
    eyebrow: `Проверка понимания ${order} из 2`,
    title: order === 1 ? "Остановись и проверь основу" : "Свяжи правило с примером",
    question: {
      text: quizQuestion.text,
      options: quizQuestion.options.map(({ isCorrect: _isCorrect, ...option }) => option),
      correctOptionId: quizQuestion.options.find((option) => option.isCorrect)!.id,
      explanation: quizQuestion.explanation,
    },
  });

  if (item.detailedPages && item.checkpointAfter) {
    const checkpointByPage = new Map<number, LessonCheckpointPage>([
      [item.checkpointAfter[0], checkpoint(firstCheck, 1)],
      [item.checkpointAfter[1], checkpoint(secondCheck, 2)],
    ]);
    return item.detailedPages.flatMap((page, index) => {
      const pageNumber = index + 1;
      const contentPage: LessonContentPage = {
        id: `${item.id}-detail-${pageNumber}`,
        kind: "CONTENT",
        sectionType: page.sectionType,
        eyebrow: page.eyebrow,
        title: page.title,
        body: page.body,
        illustration: page.illustration,
      };
      const check = checkpointByPage.get(pageNumber);
      return check ? [contentPage, check] : [contentPage];
    });
  }

  const [intro, steps, example, takeaway] = item.sections;
  if (!intro || !steps || !example || !takeaway) return [];

  const commonMistake = finalQuestion.options.find((option) => !option.isCorrect)?.text ?? "делать вывод по одному признаку";
  const depthNote = depthNotes[item.id] ?? "Свяжи определение с конкретным действием: что именно происходит, кто проверяет правило и какой риск остаётся. Такое объяснение полезнее заученного термина, потому что помогает распознать похожую ситуацию в жизни.";

  return [
    { id: `${item.id}-intro`, kind: "CONTENT", sectionType: "TEXT", eyebrow: "Шаг 1 · Основа", title: intro.title ?? "Сначала главное", body: intro.body },
    { id: `${item.id}-mechanics`, kind: "CONTENT", sectionType: "BULLETS", eyebrow: "Шаг 2 · Механика", title: steps.title ?? "Как это работает", body: steps.body },
    checkpoint(firstCheck, 1),
    { id: `${item.id}-depth`, kind: "CONTENT", sectionType: "TEXT", eyebrow: "Шаг 3 · Чуть глубже", title: "Что скрывается за коротким определением", body: depthNote },
    { id: `${item.id}-example`, kind: "CONTENT", sectionType: "EXAMPLE", eyebrow: "Шаг 4 · На практике", title: example.title ?? "Разберём ситуацию", body: example.body },
    checkpoint(secondCheck, 2),
    {
      id: `${item.id}-risk`,
      kind: "CONTENT",
      sectionType: "RISK",
      eyebrow: "Шаг 5 · Граница знания",
      title: "Где легко сделать неверный вывод",
      body: `Опасное упрощение: «${commonMistake}». ${finalQuestion.explanation} Одного признака недостаточно для решения: сначала отдели проверенный факт от предположения и оцени, что может пойти не так.`,
    },
    { id: `${item.id}-summary`, kind: "CONTENT", sectionType: "KEY_TAKEAWAY", eyebrow: "Шаг 6 · Итог", title: takeaway.title ?? "Соберём всё вместе", body: `${takeaway.body}\n\n${item.robotTip}` },
  ];
}

