type LessonStatus = "NOT_STARTED" | "OPENED" | "COMPLETED";
type SectionType = "TEXT" | "EXAMPLE" | "KEY_TAKEAWAY" | "RISK" | "BULLETS";

type LessonSection = { type: SectionType; title?: string; body: string };
type LessonContentPage = {
  id: string;
  kind: "CONTENT";
  sectionType: SectionType;
  eyebrow: string;
  title: string;
  body: string;
  illustration?: CryptoLessonPageSpec["illustration"];
};
type LessonCheckpointPage = {
  id: string;
  kind: "CHECKPOINT";
  eyebrow: string;
  title: string;
  question: {
    text: string;
    options: Array<{ id: string; text: string }>;
    correctOptionId: string;
    explanation: string;
  };
};
type LessonPage = LessonContentPage | LessonCheckpointPage;
type QuizOption = { id: string; text: string; isCorrect: boolean };
type QuizQuestion = {
  id: string;
  text: string;
  type: "SINGLE_CHOICE";
  explanation: string;
  options: QuizOption[];
};
type LessonRecord = {
  id: string;
  courseId: string;
  title: string;
  shortDescription: string;
  durationMinutes: number;
  order: number;
  sections: LessonSection[];
  detailedPages?: CryptoLessonPageSpec[];
  checkpointAfter?: [number, number];
  robotTip: string;
  quiz: { id: string; title: string; questions: QuizQuestion[] };
};

