function question(id: string, text: string, correct: string, wrong: [string, string], explanation: string): QuizQuestion {
  return {
    id,
    text,
    type: "SINGLE_CHOICE",
    explanation,
    options: [
      { id: `${id}-a`, text: correct, isCorrect: true },
      { id: `${id}-b`, text: wrong[0], isCorrect: false },
      { id: `${id}-c`, text: wrong[1], isCorrect: false },
    ],
  };
}

function lesson(
  id: string,
  courseId: string,
  order: number,
  title: string,
  shortDescription: string,
  intro: string,
  steps: string,
  example: string,
  takeaway: string,
  robotTip: string,
  questions: QuizQuestion[],
): LessonRecord {
  return {
    id,
    courseId,
    order,
    title,
    shortDescription,
    durationMinutes: [8, 9, 10, 11, 12][order - 1] ?? 9,
    robotTip,
    sections: [
      { type: "TEXT", title: "Разберёмся без сложных слов", body: intro },
      { type: "BULLETS", title: "По шагам", body: steps },
      { type: "EXAMPLE", title: "Пример", body: example },
      { type: "KEY_TAKEAWAY", title: "Главное запомнить", body: takeaway },
    ],
    quiz: { id: `quiz-${id}`, title: `Мини-тест: ${title}`, questions },
  };
}

function expandedCryptoLesson(spec: CryptoLessonSpec): LessonRecord {
  const questions = spec.questions.map((item) => question(item.id, item.text, item.correct, item.wrong, item.explanation));
  return {
    id: spec.id,
    courseId: "crypto-basics",
    order: spec.order,
    title: spec.title,
    shortDescription: spec.shortDescription,
    durationMinutes: spec.durationMinutes,
    robotTip: spec.robotTip,
    sections: spec.pages.map((page) => ({ type: page.sectionType, title: page.title, body: page.body })),
    detailedPages: spec.pages,
    checkpointAfter: spec.checkpointAfter,
    quiz: { id: `quiz-${spec.id}`, title: `Итоговый тест: ${spec.title}`, questions },
  };
}

