export async function submitQuiz(quizId: string, answers: Array<{ questionId: string; optionIds: string[] }>, currentUser: AppUser) {
  const item = lessons.find((candidate) => candidate.quiz.id === quizId);
  if (!item || answers.length !== item.quiz.questions.length) return undefined;

  const allQuestionsAnswered = item.quiz.questions.every((quizQuestion) => {
    const matchingAnswers = answers.filter((answer) => answer.questionId === quizQuestion.id);
    const selectedIds = matchingAnswers[0]?.optionIds ?? [];
    return matchingAnswers.length === 1
      && selectedIds.length === 1
      && quizQuestion.options.some((option) => option.id === selectedIds[0]);
  });
  if (!allQuestionsAnswered) return undefined;

  let correctAnswers = 0;
  const details = item.quiz.questions.map((quizQuestion) => {
    const answer = answers.find((candidate) => candidate.questionId === quizQuestion.id);
    const correctIds = quizQuestion.options.filter((option) => option.isCorrect).map((option) => option.id);
    const selectedIds = answer?.optionIds ?? [];
    const correct = selectedIds.length === correctIds.length && correctIds.every((id) => selectedIds.includes(id));
    if (correct) correctAnswers += 1;
    return {
      questionId: quizQuestion.id,
      questionText: quizQuestion.text,
      correct,
      explanation: quizQuestion.explanation,
      correctOptionIds: correctIds,
      selectedOptionText: quizQuestion.options.find((option) => selectedIds.includes(option.id))?.text ?? "Ответ не выбран",
      correctOptionText: quizQuestion.options.find((option) => option.isCorrect)?.text ?? "",
    };
  });

  const scorePercent = Math.round((correctAnswers / item.quiz.questions.length) * 100);
  const passed = scorePercent >= 67;
  const completedAt = new Date().toISOString();
  await progressRepository?.recordQuizAttempt(currentUser.id, currentUser.displayName, {
    quizId,
    lessonId: item.id,
    correctAnswers,
    totalQuestions: item.quiz.questions.length,
    scorePercent,
    answers,
    completedAt,
  }, passed);
  const snapshot = await snapshotFor(currentUser);
  const courseLessons = lessons.filter((candidate) => candidate.courseId === item.courseId).sort((a, b) => a.order - b.order);
  const currentIndex = courseLessons.findIndex((candidate) => candidate.id === item.id);
  const nextLessonId = courseLessons[currentIndex + 1]?.id ?? null;

  return {
    lessonId: item.id,
    courseId: item.courseId,
    correctAnswers,
    totalQuestions: item.quiz.questions.length,
    scorePercent,
    passed,
    passingScorePercent: 67,
    completedLesson: snapshot.completedLessonIds.includes(item.id),
    details,
    courseProgress: progressFor(snapshot, item.courseId),
    overallProgress: progressFor(snapshot),
    nextLessonId: snapshot.completedLessonIds.includes(item.id) ? nextLessonId : null,
  };
}

